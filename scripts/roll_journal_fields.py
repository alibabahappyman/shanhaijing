def roll(file, table):
    p = 'src/data/' + file
    with open(p, encoding='utf-8') as f:
        v = json.load(f)
    n = 0
    for s in v['scenes']:
        d = table.get(s['id'])
        if not d:
            print('MISSING', file, s['id']); continue
        s['fullText'], s['fullSource'], s['storyTranslation'], s['translation'] = d
        n += 1
    with io.open(p, 'w', encoding='utf-8') as f:
        json.dump(v, f, ensure_ascii=False, indent=2)
        f.write('\n')
    print(file, n, 'updated')

